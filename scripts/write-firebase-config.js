/**
 * Reads the live web SDK config out of Firebase and writes app/firebase-config.js.
 *
 * Run by scripts/setup-firebase.sh; usable on its own if you ever need to
 * re-sync the config:
 *   node scripts/write-firebase-config.js <project-id>
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectId = process.argv[2];
if (!projectId) {
  console.error('usage: node scripts/write-firebase-config.js <project-id>');
  process.exit(1);
}

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function firebase(args) {
  return execFileSync(process.platform === 'win32' ? 'firebase.cmd' : 'firebase', args, {
    encoding: 'utf8',
    maxBuffer: 10 * 1024 * 1024,
  });
}

// Find the web app id, then ask for its SDK config as JSON.
const appsRaw = firebase(['apps:list', 'WEB', '--project', projectId, '--json']);
const apps = JSON.parse(appsRaw);
const list = apps.result || [];
if (!list.length) {
  console.error('No WEB app found in ' + projectId + '. Run: firebase apps:create WEB "PastaPronto Web" --project ' + projectId);
  process.exit(1);
}
const appId = list[0].appId;

const sdkRaw = firebase(['apps:sdkconfig', 'WEB', appId, '--project', projectId, '--json']);
const sdk = JSON.parse(sdkRaw);
const cfg = (sdk.result && (sdk.result.sdkConfig || sdk.result)) || {};

const required = ['apiKey', 'authDomain', 'projectId', 'appId'];
const missing = required.filter((k) => !cfg[k]);
if (missing.length) {
  console.error('SDK config is missing: ' + missing.join(', '));
  console.error(JSON.stringify(cfg, null, 2));
  process.exit(1);
}

const body = `/**
 * Firebase web config for PastaPronto.
 *
 * These values are NOT secret - Firebase web config is designed to ship to the
 * browser, and every visitor can read it. What protects your data is
 * firestore.rules, not this file.
 *
 * Generated by scripts/write-firebase-config.js. Re-run it to re-sync.
 */
export const firebaseConfig = {
  apiKey: ${JSON.stringify(cfg.apiKey)},
  authDomain: ${JSON.stringify(cfg.authDomain)},
  projectId: ${JSON.stringify(cfg.projectId)},
  storageBucket: ${JSON.stringify(cfg.storageBucket || '')},
  messagingSenderId: ${JSON.stringify(cfg.messagingSenderId || '')},
  appId: ${JSON.stringify(cfg.appId)},
};

/** True once real values are in place, so screens can show a helpful message. */
export const isConfigured = !Object.values(firebaseConfig).some(
  (v) => typeof v === 'string' && v.includes('REPLACE_ME'),
);
`;

fs.writeFileSync(path.join(ROOT, 'app', 'firebase-config.js'), body);
console.log('      app/firebase-config.js <- ' + cfg.projectId + ' (app ' + appId + ')');
